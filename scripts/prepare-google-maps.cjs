const fs = require('node:fs');
const path = require('node:path');
const { parseEnv } = require('node:util');
const root = path.resolve(__dirname, '..');
const envPath = path.join(root, '.env');
const fileEnv = fs.existsSync(envPath)
  ? parseEnv(fs.readFileSync(envPath, 'utf8'))
  : {};
const local = path.join(root, 'config/google-maps.local.json');
const config = fs.existsSync(local)
  ? JSON.parse(fs.readFileSync(local, 'utf8'))
  : {};
const ios =
  process.env.GOOGLE_MAPS_IOS_API_KEY ||
  fileEnv.GOOGLE_MAPS_IOS_API_KEY ||
  config.iosApiKey ||
  '';
const android =
  process.env.GOOGLE_MAPS_ANDROID_API_KEY ||
  fileEnv.GOOGLE_MAPS_ANDROID_API_KEY ||
  config.androidApiKey ||
  '';
for (const key of [ios, android]) {
  if (key && !/^AIza[\w-]+$/.test(key)) {
    throw new Error(
      'Google Maps Platform 키를 입력하세요. Stitch 키는 사용할 수 없습니다.',
    );
  }
}
fs.mkdirSync(path.join(root, 'src/config'), { recursive: true });
fs.writeFileSync(
  path.join(root, 'src/config/googleMaps.generated.ts'),
  `// Generated by maps:configure. Contains no API keys.\nexport const googleMapsConfigured = { ios: ${!!ios}, android: ${!!android} };\n`,
);
fs.writeFileSync(
  path.join(root, 'ios/GoogleMaps.local.xcconfig'),
  `GOOGLE_MAPS_API_KEY = ${ios}\n`,
);
fs.writeFileSync(
  path.join(root, 'android/google-maps.local.properties'),
  `apiKey=${android}\n`,
);
console.log(
  `Google Maps 설정: iOS ${ios ? '준비됨' : '키 없음'}, Android ${android ? '준비됨' : '키 없음'}`,
);
